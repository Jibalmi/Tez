def hub_licence(repo: str, kind: str) -> str | None:
    from huggingface_hub import HfApi
    api = HfApi()
    try:
        info = api.dataset_info(repo) if kind == "dataset" else api.model_info(repo)
    except Exception as exc:  # noqa: BLE001
        return f"lookup failed: {type(exc).__name__}"
    card = getattr(info, "card_data", None) or getattr(info, "cardData", None)
    lic = None
    if card is not None:
        lic = card.get("license") if hasattr(card, "get") else getattr(card, "license", None)
    if lic is None:
        lic = next((t.split(":", 1)[1] for t in (info.tags or []) if t.startswith("license:")), None)
    return ", ".join(lic) if isinstance(lic, list) else lic


def main() -> None:
    today = dt.date.today().isoformat()
    rows = []
    for repo, kind, use, notes in ENTRIES:
        url = f"https://huggingface.co/{'datasets/' if kind == 'dataset' else ''}{repo}"
        lic = hub_licence(repo, kind)
        rows.append({"id": repo, "kind": kind, "use": use, "licence": lic, "url": url, "notes": notes})
        print(f"{use:16s} {repo:62s} {lic}")
    dump(RESULTS / "licences.json", {
        "title": "Small-model pilot: licence ledger",
        "fetched": today,
        "rule": "training entries only feed training; evaluation-only entries are hashed by the leakage guard and never enter training",
        "entries": rows + LOCAL,
        "excluded": EXCLUDED,
    })


if __name__ == "__main__":
    main()
